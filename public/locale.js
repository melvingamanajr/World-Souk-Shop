const storageKey = 'wss-locale';

function storedLanguage() {
  try {
    return globalThis.localStorage?.getItem(storageKey) === 'zh-CN' ? 'zh-CN' : 'en';
  } catch {
    return 'en';
  }
}

let language = storedLanguage();

export function locale() {
  return language;
}

export function t(key, values = {}) {
  const translated = language === 'zh-CN' && Object.hasOwn(chinese, key) ? chinese[key] : key;
  return String(translated).replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : placeholder
  ));
}

export function setLocale(value) {
  if (!['en', 'zh-CN'].includes(value) || language === value) return language;
  language = value;
  try {
    globalThis.localStorage?.setItem(storageKey, value);
  } catch {
    // Language still applies to this page when persistent storage is unavailable.
  }
  if (typeof document !== 'undefined') localizeShell();
  if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent('wss-language', { detail: { locale: language } }));
  return language;
}

function showToggle() {
  const nav = document.querySelector('.main-nav');
  if (!nav) return;
  let button = nav.querySelector('#language-toggle');
  if (!button) {
    button = document.createElement('button');
    button.type = 'button';
    button.id = 'language-toggle';
    button.className = 'button button-text locale-switch';
    button.append(document.createElement('span'));
    button.addEventListener('click', () => setLocale(language === 'en' ? 'zh-CN' : 'en'));
    nav.append(button);
  }
  const target = language === 'en' ? 'zh-CN' : 'en';
  const label = button.querySelector('span');
  label.lang = target;
  label.textContent = target === 'zh-CN' ? '简体中文' : 'English';
  button.title = t(target === 'zh-CN' ? 'Switch to Simplified Chinese' : 'Switch to English');
}

export function localizeShell() {
  document.documentElement.lang = language;
  document.title = t('World Souk & Shop | Factory-direct marketplace');

  for (const [selector, key] of textBindings) {
    for (const element of document.querySelectorAll(selector)) element.textContent = t(key);
  }
  for (const [selector, attribute, key] of attributeBindings) {
    for (const element of document.querySelectorAll(selector)) element.setAttribute(attribute, t(key));
  }
  for (const [selector, key] of textNodeBindings) {
    const node = Array.from(document.querySelector(selector)?.childNodes ?? []).find(child => child.nodeType === Node.TEXT_NODE && child.nodeValue.trim());
    if (node) node.nodeValue = ` ${t(key)}`;
  }

  const heading = document.querySelector('#hero-title');
  if (heading) {
    const plainText = Array.from(heading.childNodes).filter(child => child.nodeType === Node.TEXT_NODE);
    if (plainText[0]) plainText[0].nodeValue = t('Closer to');
    if (plainText[1]) plainText[1].nodeValue = t('the ');
    const emphasis = heading.querySelector('em');
    if (emphasis) emphasis.textContent = t('maker.');
  }

  const signin = document.querySelector('#signin-button');
  const signinKey = ['Sign in', 'Your account'].find(key => [key, chinese[key]].includes(signin?.textContent.trim()));
  if (signinKey) signin.textContent = t(signinKey);
  const status = document.querySelector('#catalog-status');
  if (status && ['Loading products…', chinese['Loading products…']].includes(status.textContent.trim())) {
    status.textContent = t('Loading products…');
  }
  showToggle();
}
